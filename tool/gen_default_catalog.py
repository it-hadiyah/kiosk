#!/usr/bin/env python3
"""يولّد lib/data/default_catalog.dart (الكتالوج المضمّن في التطبيق) من server/seed/catalog.json.
الصور تتحول من /uploads/x.jpg إلى asset:assets/images/x.jpg."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
seed = (root / 'server/seed/catalog.json').read_text(encoding='utf-8')
seed = re.sub(r'"/uploads/([\w.\-]+)"', r'"asset:assets/images/\1"', seed)
json.loads(seed)  # تحقق
out = "// GENERATED by tool/gen_default_catalog.py — لا تعدّله يدوياً.\n// الكتالوج المضمّن: يُستخدم عند عدم توفر الخادم أو قبل أول مزامنة.\n\nconst kDefaultCatalogJson = r'''" + seed + "''';\n"
(root / 'lib/data/default_catalog.dart').write_text(out, encoding='utf-8')
print('ok', len(out))
